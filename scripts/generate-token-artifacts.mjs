import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sources = [
  { file: 'cvp-primitives.css', tier: 'Primitive' },
  { file: 'cvp-semantic-tokens.css', tier: 'Semantic' },
  { file: 'cvp-component-tokens.css', tier: 'Component' },
];

const read = path => readFileSync(resolve(root, path), 'utf8');
const escapeMarkdown = value => value.replaceAll('`', '\\`').replaceAll('|', '\\|');

function scopeBefore(source, index) {
  const preceding = source.slice(0, index);
  const lastDark = Math.max(preceding.lastIndexOf(':root:not('), preceding.lastIndexOf('[data-theme="dark"]'));
  const lastLight = preceding.lastIndexOf('[data-theme="light"]');
  return lastLight > lastDark ? 'Light theme' : lastDark >= 0 ? 'Dark theme' : 'Shared';
}

function parseTokens({ file, tier }) {
  const source = read(`src/styles/tokens/${file}`);
  const declaration = /(--cvp-[\w-]+)\s*:\s*([^;]+);/g;
  return [...source.matchAll(declaration)].map(match => ({
    name: match[1],
    value: match[2].replace(/\s*\/\*[^]*?\*\//g, '').replace(/\s+/g, ' ').trim(),
    scope: scopeBefore(source, match.index),
    tier,
    source: file,
  }));
}

const tokens = sources.flatMap(parseTokens);
const uniqueByName = Object.values(Object.groupBy(tokens, token => token.name)).flatMap(group => group);

function markdownTable(rows) {
  return [
    '| Token | Value | Scope |',
    '| --- | --- | --- |',
    ...rows.map(token => `| \`${escapeMarkdown(token.name)}\` | \`${escapeMarkdown(token.value)}\` | ${token.scope} |`),
  ].join('\n');
}

function componentGroupName(token) {
  if (token.name.startsWith('--cvp-tag-filter-')) return 'tag-filter';
  return token.name.replace(/^--cvp-/, '').split('-')[0];
}

function buildCatalog() {
  const byTier = Object.groupBy(tokens, token => token.tier);
  const catalog = [
    '# CVP Token Catalog',
    '',
    '**Status:** Current implementation inventory  ',
    '**Source of truth:** `src/styles/tokens/*.css`  ',
    '**Generated by:** `npm run tokens:generate`',
    '',
    'This catalog is the readable index of every active CVP token. It preserves each token’s defined value and theme scope. Use semantic and component tokens in product work; primitives are private source values.',
    '',
    '## How to use this catalog',
    '',
    '- **Primitive tokens** are raw values used only by token definitions.',
    '- **Semantic tokens** provide shared intent and may resolve differently in light and dark themes.',
    '- **Component tokens** are the stable API used by a component’s styles and approved overrides.',
    '- A token listed more than once has a theme-specific definition; use its semantic name, not the theme value directly.',
    '',
    '## Inventory',
    '',
    '| Tier | Source file | Definitions |',
    '| --- | --- | ---: |',
    ...sources.map(({ file, tier }) => `| ${tier} | \`${file}\` | ${byTier[tier].length} |`),
    '',
  ];

  catalog.push('## Tier 1 — Primitive tokens', '', 'Raw colour, spacing, typography, motion, elevation, and opacity values. Do not reference these from component CSS.', '', markdownTable(byTier.Primitive), '');
  catalog.push('## Tier 2 — Semantic tokens', '', 'Intent-based roles. Theme-specific rows are shown with their scope so the light and dark mappings remain visible.', '');
  for (const [scope, rows] of Object.entries(Object.groupBy(byTier.Semantic, token => token.scope))) {
    catalog.push(`### ${scope}`, '', markdownTable(rows), '');
  }
  catalog.push('## Tier 3 — Component tokens', '', 'Component contracts. Each group is named after the component or shared contract prefix.', '');
  const componentGroups = Object.entries(Object.groupBy(byTier.Component, componentGroupName)).sort(([a], [b]) => a.localeCompare(b));
  for (const [name, rows] of componentGroups) {
    catalog.push('<details>', `<summary><strong>${name}</strong> — ${rows.length} tokens</summary>`, '', markdownTable(rows), '', '</details>', '');
  }
  catalog.push('## Maintenance rules', '', '1. Add a raw value only when it is reusable across semantic roles.', '2. Add a semantic token when the product needs a stable meaning that may change by theme.', '3. Add a component token only for a documented component decision, state, or supported override.', '4. Run `npm run tokens:generate` whenever a token definition changes. CI should run `npm run tokens:check` to prevent drift.', '');
  return catalog.join('\n');
}

function buildRegistry() {
  return `${JSON.stringify({
    version: 1,
    source: 'src/styles/tokens/*.css',
    tokens: uniqueByName.map(({ name, tier, scope, source }) => ({ name, tier, scope, source })),
  }, null, 2)}\n`;
}

const outputs = [
  { path: 'docs/tokens/TOKEN_CATALOG.md', content: buildCatalog() },
  { path: 'src/styles/token-registry.json', content: buildRegistry() },
];
const check = process.argv.includes('--check');
const stale = outputs.filter(({ path, content }) => !existsSync(resolve(root, path)) || read(path) !== content);

if (check) {
  if (stale.length) {
    console.error(`Token artifacts are out of date: ${stale.map(({ path }) => path).join(', ')}. Run npm run tokens:generate.`);
    process.exit(1);
  }
  console.log(`Token artifacts are current (${tokens.length} definitions across ${sources.length} source files).`);
} else {
  for (const { path, content } of outputs) writeFileSync(resolve(root, path), content);
  console.log(`Generated ${outputs.map(({ path }) => path).join(' and ')}.`);
}
